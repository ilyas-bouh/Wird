"""Copy the test MP3s into assets/audio and generate src/data/audioAssets.ts.
usage: python -I -X utf8 tools/bundle_test_audio.py <audio_out_dir>   (dir containing audio_index.json + mp3/)
Test set: reciter alkazabri, 1:1-1:7 and 2:1-2:110 (matches the bundled test pages)."""
import json, os, shutil, sys

src = sys.argv[1]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = json.load(open(os.path.join(src, 'audio_index.json'), encoding='utf-8'))
sel = [x for x in d['ayahs'] if x['reciter'] == 'alkazabri' and (x['surah'] == 1 or (x['surah'] == 2 and x['ayah'] <= 110))]
os.makedirs(os.path.join(root, 'assets', 'audio'), exist_ok=True)
for x in sel:
    shutil.copy(os.path.join(src, 'mp3', x['file']), os.path.join(root, 'assets', 'audio', x['file']))
lines = [
    "// Generated by tools/bundle_test_audio.py: test audio (reciter alkazabri, 1:1-1:7 and 2:1-2:110).",
    "// The full set will be downloaded later. Keys are 'surah:ayah' in Warsh numbering.",
    "",
    "export const AYAH_AUDIO: Record<string, number> = {",
]
for x in sel:
    lines.append(f"  '{x['surah']}:{x['ayah']}': require('../../assets/audio/{x['file']}'),")
lines += ["};", ""]
open(os.path.join(root, 'src', 'data', 'audioAssets.ts'), 'w', encoding='utf-8').write("\n".join(lines))
print(len(sel), 'files')
